CREATE TABLE public.brands (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text,
  logo_url text,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT brands_pkey PRIMARY KEY (id)
);
CREATE TABLE public.motos (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  brand_id uuid NOT NULL,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  model_year integer NOT NULL CHECK (model_year >= 1900),
  category USER-DEFINED NOT NULL,
  tagline text NOT NULL,
  description text NOT NULL,
  featured_image text NOT NULL,
  gallery_images ARRAY DEFAULT '{}'::text[],
  features ARRAY DEFAULT '{}'::text[],
  warranty_info text NOT NULL,
  soat_category USER-DEFINED NOT NULL,
  pays_vehicle_tax boolean NOT NULL DEFAULT false,
  price_base numeric NOT NULL CHECK (price_base >= 0::numeric),
  price_estimated_paperwork numeric NOT NULL CHECK (price_estimated_paperwork >= 0::numeric),
  price_total_estimated numeric NOT NULL CHECK (price_total_estimated >= 0::numeric),
  price_updated_at text NOT NULL,
  engine_displacement numeric NOT NULL CHECK (engine_displacement > 0::numeric),
  engine_type text NOT NULL,
  engine_max_power_hp numeric NOT NULL,
  engine_max_power_rpm integer NOT NULL,
  engine_max_torque_nm numeric NOT NULL,
  engine_max_torque_rpm integer NOT NULL,
  engine_cooling USER-DEFINED NOT NULL,
  engine_fuel_system USER-DEFINED NOT NULL,
  engine_transmission text NOT NULL,
  engine_clutch text,
  chassis_frame_type text,
  chassis_front_brake text NOT NULL,
  chassis_rear_brake text NOT NULL,
  chassis_abs USER-DEFINED NOT NULL,
  chassis_front_suspension text NOT NULL,
  chassis_rear_suspension text NOT NULL,
  chassis_front_tire text NOT NULL,
  chassis_rear_tire text NOT NULL,
  dim_kerb_weight_kg numeric NOT NULL,
  dim_seat_height_mm integer NOT NULL,
  dim_tank_capacity_liters numeric NOT NULL,
  dim_tank_capacity_gal numeric NOT NULL,
  dim_ground_clearance_mm integer,
  dim_estimated_consumption_km_gal numeric,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT motos_pkey PRIMARY KEY (id),
  CONSTRAINT motos_brand_id_fkey FOREIGN KEY (brand_id) REFERENCES public.brands(id)
);